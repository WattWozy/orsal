import generated from "@/src/data/generated.json";

export type Unit = "m" | "m²" | "ud";

export interface SpecificProduct {
  id: string;
  name: string;
  description: string;
  specs: string[];
  requiresAssembly?: boolean;
  unit: Unit;
  pricingConfigured: boolean;
  salePrice: number | null;
}

export interface ProductCategory {
  id: string;
  title: string;
  tagline: string;
  description: string;
  products: SpecificProduct[];
}

interface GeneratedProduct {
  id: string;
  name: string;
  description?: string | null;
  unit?: string | null;
  pricingConfigured: boolean;
  salePrice: number | null;
}

interface GeneratedFamily {
  id: string;
  title: string;
  products: GeneratedProduct[];
}

interface GeneratedCatalog {
  generatedAt: string;
  currency: string;
  pricing: { laborRate: number; margin: number };
  families: GeneratedFamily[];
}

const data = generated as unknown as GeneratedCatalog;

/* ---------- Optional editorial content, keyed by id from the Excel ---------- */

const FAMILY_META: Record<string, { tagline: string; description: string }> = {
  // key = family id as generated by slugify(Familia)
  "cercados-metalicos-y-mallas": {
    tagline: "Cerramientos perimetrales flexibles y tradicionales",
    description:
      "Sistemas clásicos para fincas, parcelas agrícolas, naves industriales y terrenos de gran extensión.",
  },
  // ...move the other families here
};

const PRODUCT_META: Record<string, { specs?: string[]; requiresAssembly?: boolean }> = {
  // key = "Código producto" from the Excel
  "malla-simple-torsion": {
    specs: [
      "Luz de malla: 50 mm",
      "Diámetro alambre: 2.7 mm / 3.4 mm",
      "Alturas disponibles: 1m, 1.5m, 2m",
    ],
  },
  // ...move the other products' specs here
};

/* ---------- Normalisation ---------- */

function normalizeUnit(raw?: string | null): Unit {
  const u = (raw ?? "").toString().trim().toLowerCase();
  if (u === "m²" || u === "m2") return "m²";
  if (u === "m" || u === "ml") return "m";
  return "ud";
}

export const CATALOG_FAMILIES: ProductCategory[] = data.families.map((family) => {
  const meta = FAMILY_META[family.id];

  return {
    id: family.id,
    title: family.title,
    tagline: meta?.tagline ?? "",
    description: meta?.description ?? "",
    products: family.products.map((p) => ({
      id: p.id,
      name: p.name,
      description: p.description ?? "",
      specs: PRODUCT_META[p.id]?.specs ?? [],
      requiresAssembly: PRODUCT_META[p.id]?.requiresAssembly,
      unit: normalizeUnit(p.unit),
      pricingConfigured: p.pricingConfigured && p.salePrice != null,
      salePrice: p.salePrice,
    })),
  };
});

export const CATALOG_INFO = {
  generatedAt: data.generatedAt,
  currency: data.currency,
};